package main;

public class Main16 {
    public static void main(String[] args) {
        int i = 1;  // Counter variable
        do{ // do-while runs the body first, then checks the condition
            System.out.println("I love to be alone!");
            i++;
        } while(i <= 5); // Repeats until i becomes greater than 5 (runs 5 times)
    }
}
