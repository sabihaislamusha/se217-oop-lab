package main;

public class Main14 {
    public static void main(String[] args) {
        int i = 1;  // Counter variable
        while (i <= 5) {  // Repeats while i is 5 or less (runs 5 times)
            System.out.println("Learning Java!");
            i++; // Increase the counter, otherwise the loop never ends
        }
    }
}
